const LangContext = createContext({
  lang: 'es',
  t: (k) => k,
  tr: (p) => p,
  catName: (n) => n,
  setLang: () => {},
});
export const useLang = () => useContext(LangContext);

function detectLang() {
  return 'es';
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(detectLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = {
    lang,
    t: (key, params) => {
      const dict = I18N[lang] || I18N.es;
      let s = dict[key] !== undefined ? dict[key] : I18N.es[key] !== undefined ? I18N.es[key] : key;
      if (params && typeof s === 'string') {
        Object.entries(params).forEach(([k, v]) => {
          s = s.split(`{${k}}`).join(v);
        });
      }
      return s;
    },
    tr: (p) => {
      if (lang === 'es' && p && p.titulo_es) {
        return { ...p, titulo: p.titulo_es, descripcion: p.descripcion_es || p.descripcion };
      }
      return p;
    },
    catName: (name) => {
      if (!name) return name;
      const dict = CATS[lang] || CATS.es;
      return dict[name] !== undefined ? dict[name] : name;
    },
    setLang: (l) => {
      if (!I18N[l]) return;
      setLangState(l);
      localStorage.setItem('lang', l);
    },
    toggleLang: () => setLangState((cur) => {
      const next = cur === 'es' ? 'en' : 'es';
      localStorage.setItem('lang', next);
      return next;
    }),
  };

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}